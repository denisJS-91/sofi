import "dotenv/config"; // 👈 ПЕРВОЙ строкой
import OpenAI from "openai";
import { enforceConsistency } from "./ai/consistencyLayer.js";

// 1. Создаём клиент OpenRouter (совместим с OpenAI SDK)
const client = new OpenAI({
  apiKey: process.env.OPENROUTER_API_KEY,
  baseURL: "https://openrouter.ai/api/v1",
  defaultHeaders: {
    "HTTP-Referer": "http://localhost:3000", // не обязательно, но рекомендуется
    "X-Title": "Sofi AI",
  },
});

