// Триггеры, после которых имеет смысл искать в интернете
const SEARCH_TRIGGERS = [
  /погод/i,
  /новост/i,
  /курс[а-я]*\s*(доллар|евро|рубл|биткоин|валют)/i,
  /сколько\s+стоит/i,
  /кто\s+так(ой|ая|ие)/i,
  /что\s+так(ое|ие)/i,
  /когда\s+(произошл|будет|начн|законч|выйд|откры)/i,
  /где\s+(находит|купить|заказать|работает)/i,
  /сегодня\s+в\s+/i,
  /последн[а-я]+\s+(новост|событ)/i,
  /что\s+случилось/i,
  /как\s+добраться/i,
  /расписани/i,
];

export function shouldSearch(message) {
  return SEARCH_TRIGGERS.some((re) => re.test(message));
}
